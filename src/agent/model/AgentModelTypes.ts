/**
 * Phase 10B.1: provider-neutral agent model types.
 *
 * No provider-native JSON or roles here. Codecs translate between these
 * canonical types and provider-specific wire formats.
 *
 * IMPORTANT: A `toolResult` is always a SUBI-host object. The model emits
 * a tool-call REQUEST; SUBI runs the tool via ToolExecutor and synthesizes
 * the `toolResult` message that is fed back into the next model turn.
 */

import type { AgentMode } from '../AgentMode';
import type { SubiAccessMode } from '../../types';

/** Canonical finish reasons normalized from provider-native stop reasons. */
export type AgentFinishReason =
  | 'stop'
  | 'tool_calls'
  | 'length'
  | 'content_filter'
  | 'error'
  | 'unknown';

/** Per-call id concept. Never treated as authority for filesystem/tool state. */
export interface AgentCallIds {
  /** SUBI-normalized id. Generated by AgentLoop. Used by ToolExecutor and UI. */
  subiCallId: string;
  /** Opaque provider-supplied id. Retained only for codec round-trip. */
  providerCallId?: string;
}

/** Tool-call request assembled by the model and validated by SUBI. */
export interface AgentModelToolCall extends AgentCallIds {
  toolName: string;
  args: Record<string, unknown>;
}

/** Safe model-facing projection of a host ToolDefinition. */
export interface AgentModelToolDefinition {
  name: string;
  description: string;
  inputSchema: AgentModelInputField[];
}

export interface AgentModelInputField {
  name: string;
  type: 'string' | 'number' | 'boolean' | 'path' | 'query';
  required: boolean;
  description: string;
  maxLength?: number;
}

/** Canonical transcript variants. Provider-agnostic. */
export type AgentModelMessage =
  | { role: 'system';          content: string }
  | { role: 'user';            content: string }
  | { role: 'assistantText';   content: string }
  | {
      role: 'assistantToolCalls';
      text: string;
      toolCalls: AgentModelToolCall[];
    }
  | {
      role: 'toolResult';
      callId: string;
      toolName: string;
      content: string;
      isError: boolean;
    };

/** Aggregated usage. Only sums reported values; never estimates. */
export interface AgentUsageAggregate {
  modelCalls: number;
  inputTokens?: number;
  outputTokens?: number;
}

/** Request to a single model turn. */
export interface AgentModelRequest {
  provider: string;
  model: string;
  messages: AgentModelMessage[];
  /** Tools the model is allowed to call. Order is preserved. */
  tools: AgentModelToolDefinition[];
  /** Tool-choice override (provider-specific semantics; codec-specific). */
  toolChoice?: string;
  /** Optional additional provider-codec hints (temperature, max_tokens, etc.). */
  hints?: Record<string, unknown>;
}

/** Canonical streaming events from AgentModelGateway. */
export type AgentModelEvent =
  | { type: 'textDelta';                  text: string }
  | { type: 'toolCallStart';              subiCallId: string; providerCallId?: string; toolName: string }
  | { type: 'toolCallArgumentsDelta';     subiCallId: string; partialArgs: string }
  | {
      type: 'toolCallReady';
      subiCallId: string;
      providerCallId?: string;
      toolName: string;
      args: Record<string, unknown>;
    }
  | { type: 'usage';                       usage: AgentUsageAggregate }
  | { type: 'finish';                      reason: AgentFinishReason; usage?: AgentUsageAggregate }
  | { type: 'completed' };

/** Canonical host result envelope produced after ToolExecutor execution. */
export interface AgentToolResult {
  /** Matches a subiCallId emitted by the gateway for the same model turn. */
  subiCallId: string;
  toolName: string;
  ok: boolean;
  /**
   * Bounded, model-facing representation. May be a string summary or a
   * structured JSON string of the tool payload. Always sized to fit model
   * transcript budget.
   */
  content: string;
  /** Tool error code on failure (provider-neutral). */
  errorCode?: string;
  /** Optional human-readable error message. */
  errorMessage?: string;
  /** Number of consecutive tool errors that led up to this call. */
  durationMs?: number;
}

/** Agent runtime status (terminal). */
export type AgentStatus =
  | 'completed'
  | 'cancelled'
  | 'limit_turn'
  | 'limit_tool'
  | 'limit_context'
  | 'limit_repeated'
  | 'error_provider'
  | 'error_mode_unavailable';

/** Snapshot of model source for diagnostics. */
export interface AgentModelSelection {
  provider: string | null;
  model: string | null;
}

/** Final outcome returned by AgentLoop.run(). */
export interface AgentRunOutcome {
  status: AgentStatus;
  finalAnswer: string;
  usage: AgentUsageAggregate;
  toolCallCount: number;
  turnCount: number;
  /** Sanitized error code (provider-neutral). */
  errorCode?: string;
  /** Sanitized error message (never includes provider internals). */
  errorMessage?: string;
}

/** Access mode snapshot for the agent run. */
export interface AgentAccessSnapshot {
  accessMode: SubiAccessMode | null;
  agentMode: AgentMode;
}
