"""Derive Subi Code icons from the supplied, unmodified PNG.

Run from any directory with Python 3 and Pillow installed. No runtime dependency
is added to the applications. Existing native icon dimensions are preserved.
"""

import base64
import io
import json
from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
source = Image.open(ROOT / "assets/brand/subi-code-source.png").convert("RGBA")
glyph = source.crop(source.getbbox())
opaque = source.getextrema()[3][0] == 255


def icon(size):
    if opaque:
        return glyph.resize(size, Image.Resampling.LANCZOS)
    image = Image.new("RGBA", size)
    mark = glyph.copy()
    mark.thumbnail((max(1, round(size[0] * 0.84)), max(1, round(size[1] * 0.84))), Image.Resampling.LANCZOS)
    image.alpha_composite(mark, ((size[0] - mark.width) // 2, (size[1] - mark.height) // 2))
    return image


def write(path, size=None):
    if path.suffix == ".png":
        size = size or Image.open(path).size
        icon(size).save(path)
    if path.suffix == ".ico":
        icon((256, 256)).save(path, sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
    if path.suffix == ".icns":
        icon((1024, 1024)).save(path)


icon((512, 512)).save(ROOT / "assets/brand/subi-code.png")
write(ROOT / "assets/brand/subi-code.ico")
buffer = io.BytesIO()
icon((256, 256)).save(buffer, format="PNG")
uri = "data:image/png;base64," + base64.b64encode(buffer.getvalue()).decode()

# A self-contained URI keeps package consumers and OAuth callbacks independent
# of public asset roots, while every pixel still comes from the supplied image.
for relative in ("packages/ui/src/components/brand-mark.ts", "packages/core/src/oauth/brand-mark.ts"):
    mark_uri = uri
    if relative.startswith("packages/ui/"):
        # In-app marks use the transparent cutout; native icons retain the supplied master.
        app_mark = Image.open(ROOT / "assets/brand/subi-code-mark-transparent.png").convert("RGBA")
        app_mark.thumbnail((256, 256), Image.Resampling.LANCZOS)
        app_buffer = io.BytesIO()
        app_mark.save(app_buffer, format="PNG")
        mark_uri = "data:image/png;base64," + base64.b64encode(app_buffer.getvalue()).decode()
        app_uri = mark_uri
    (ROOT / relative).write_text(
        '// Generated by script/brand-assets.py; the app uses the transparent cutout.\n'
        + "export const brandMark = " + json.dumps(mark_uri) + "\n", encoding="utf-8", newline="\n"
    )

for channel in ("dev", "beta", "prod"):
    for path in (ROOT / "packages/desktop/icons" / channel).rglob("*"):
        if path.suffix in (".png", ".ico", ".icns"):
            write(path)

for directory in ("packages/ui/src/assets/favicon", "packages/app/public", "packages/web/public", "packages/console/app/public"):
    for path in (ROOT / directory).iterdir():
        if path.suffix in (".png", ".ico") and path.name.startswith(("favicon", "apple-touch-icon", "web-app-manifest")):
            write(path)
        if path.suffix == ".svg" and path.name.startswith("favicon"):
            path.write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><image width="256" height="256" href="{uri}"/></svg>\n', encoding="utf-8", newline="\n")

for name in ("icon.png", "button.png"):
    write(ROOT / "sdks/vscode/images" / name, (256, 256) if name == "icon.png" else (32, 32))
for name in ("button-dark.svg", "button-light.svg"):
    style = ' style="filter:brightness(0.3)"' if name == "button-light.svg" else ""
    (ROOT / "sdks/vscode/images" / name).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><image width="256" height="256" href="{app_uri}"{style}/></svg>\n', encoding="utf-8", newline="\n")

for relative in ("packages/web/src/assets/logo-light.svg", "packages/web/src/assets/logo-dark.svg", "packages/posts/public/logo-dark.svg"):
    color = "#161616" if "light" in relative else "#f4f4f4"
    (ROOT / relative).write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 234 42"><image width="36" height="42" href="{uri}"/><text x="42" y="29" fill="{color}" font-family="monospace" font-size="26" font-weight="700">SUBI CODE</text></svg>\n', encoding="utf-8", newline="\n")

# Two vertical pixels per terminal cell preserve the logo's aspect ratio.
# Null pixels use the terminal's current theme background.
small = icon((16, 16))
rows = []
for y in range(0, 16, 2):
    row = []
    for x in range(16):
        pixels = [small.getpixel((x, y + dy)) for dy in (0, 1)]
        row.append(["#%02x%02x%02x" % p[:3] if p[3] >= 96 else None for p in pixels])
    rows.append(row)
(ROOT / "packages/tui/src/brand-mark.ts").write_text(
    '// Generated by script/brand-assets.py; two image pixels per terminal cell.\n'
    + "export const brandMark = " + json.dumps(rows, separators=(",", ":")) + " as const\n", encoding="utf-8", newline="\n"
)

# Small monochrome fallback for update-preflight and plain terminal splash.
mono = icon((7, 6))
lines = ["       "]
def visible(pixel):
    return pixel[3] >= 96 and (not opaque or sum(pixel[:3]) / 3 >= 96)

for y in range(0, 6, 2):
    lines.append("".join(" ▄▀█"[(int(visible(mono.getpixel((x, y)))) * 2) + int(visible(mono.getpixel((x, y + 1))))] for x in range(7)))
path = ROOT / "packages/tui/src/logo.ts"
text = path.read_text(encoding="utf-8", newline="\n")
path.write_text(text[:text.index("export const go")] + "export const go = " + json.dumps({"left": lines, "right": lines}, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
print("Generated Subi Code platform, browser, extension and terminal assets")
